'use strict';
const assert = require('node:assert/strict');
global.window = global;
require('../flashcard-interaction.js');

const handlers = {};
const card = {
  id: 'fcPerspective',
  clientWidth: 300,
  style: {},
  classList: {
    add() {}, remove() {}, toggle() {}
  },
  addEventListener(name, handler) { handlers[name] = handler; }
};
let flips = 0;
let goods = 0;
let agains = 0;
const interaction = global.KawaiiFlashcardInteraction.attach(card, {
  isBusy: () => false,
  onFlip: () => { flips += 1; },
  onGood: () => { goods += 1; },
  onAgain: () => { agains += 1; }
});
const target = { closest: () => null };
const event = (pointerId, clientX, clientY = 100) => ({
  pointerId, pointerType: 'touch', button: 0, clientX, clientY, target
});

(async () => {
  // A short horizontal drag should not rate the card and must not poison a later tap.
  handlers.pointerdown(event(1, 100));
  handlers.pointermove(event(1, 130));
  handlers.pointerup(event(1, 130));
  await new Promise(resolve => setTimeout(resolve, 170));
  handlers.click({ target });
  assert.equal(flips, 1, 'next deliberate tap must still flip after a drag with no click event');
  assert.equal(goods, 0);

  // A real swipe rates once; its synthetic click is suppressed, but the next tap works.
  handlers.pointerdown(event(2, 100));
  handlers.pointermove(event(2, 220));
  handlers.pointerup(event(2, 220));
  assert.equal(goods, 1);
  handlers.click({ target });
  assert.equal(flips, 1, 'click generated by swipe must not flip the card');
  await new Promise(resolve => setTimeout(resolve, 170));
  handlers.click({ target });
  assert.equal(flips, 2, 'stale swipe suppression must expire');

  // Pointer cancellation clears the suppression state immediately.
  handlers.pointerdown(event(3, 100));
  handlers.pointermove(event(3, 150));
  handlers.pointercancel(event(3, 150));
  handlers.click({ target });
  assert.equal(flips, 3, 'pointercancel must not swallow the next tap');
  assert.equal(agains, 0);
  interaction.clearClickSuppression();
  console.log('PASS: short drag, accepted swipe, delayed click suppression expiry and pointercancel do not swallow the next iOS tap.');
})().catch(error => { console.error(error); process.exit(1); });
