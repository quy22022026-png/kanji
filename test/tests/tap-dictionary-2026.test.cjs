'use strict';
const assert = require('node:assert/strict');
global.window = global;
require('../meaning.js');
const index = new Map([['整理しました',{}],['書類',{}],['机',{}],['上',{}],['京都',{}],['世界中',{}]]);
const m = global.KawaiiMeaningModule.create({getDictionaryIndex:()=>index});
const a = m.tokenize('週末に机の上の本や書類をきれいに整理しました。').map(x=>x.text);
const b = m.tokenize('京都には毎年世界中から多くの人が観光に来ます。').map(x=>x.text);
assert.equal(a.join(''),'週末に机の上の本や書類をきれいに整理しました。');
assert.equal(b.join(''),'京都には毎年世界中から多くの人が観光に来ます。');
assert(a.includes('整理しました'));assert(a.includes('書類'));assert(b.includes('京都'));assert(b.includes('世界中'));
console.log('PASS:',JSON.stringify({a,b}));
