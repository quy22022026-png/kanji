'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const sql = fs.readFileSync(path.join(__dirname, '..', 'supabase-schema.sql'), 'utf8');
const cloud = fs.readFileSync(path.join(__dirname, '..', 'cloud-sync.js'), 'utf8');
assert.match(sql, /primary key \(user_id, id\)/i);
assert.match(cloud, /onConflict: 'user_id,id'/);
assert.match(sql, /enable row level security/i);
assert.match(sql, /auth\.uid\(\) = user_id/i);
console.log('PASS: completed sessions use a per-user composite key; upsert target and RLS remain aligned.');
