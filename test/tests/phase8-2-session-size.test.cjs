'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs'),path=require('node:path');
const root=path.join(__dirname,'..');
const app=fs.readFileSync(path.join(root,'app.js'),'utf8');
const session=fs.readFileSync(path.join(root,'study-session.js'),'utf8');
const html=fs.readFileSync(path.join(root,'index.html'),'utf8');
assert.match(html,/id="sessionSizeSelect"/);
assert.match(app,/sessionSizeSelect\.disabled = false/);
assert.match(app,/sessionSizeSelect\.onchange = \(\) =>/);
assert.match(app,/state\.prefs\.sessionSize = Number\(selected\)/);
assert.match(app,/savePrefs\(\)/);
assert.match(app,/getSessionWordLimit\(pool\.length\)/);
assert.match(app,/active\s*\?\s*`Đã lưu/);
assert.match(session,/const defaultLimit = 1000/);
console.log('PASS: session-size selector enabled, validates and persists 10/20/30/unlimited; setting applies to next session and supports limits above 10.');
