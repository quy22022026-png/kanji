'use strict';
const assert = require('node:assert/strict');
global.window = global;
global.URL.createObjectURL = () => 'blob:kana-test';
global.URL.revokeObjectURL = () => {};
global.Audio = class { constructor(src) { this.src = src; this.paused = true; } async play() { this.paused = false; } pause() { this.paused = true; } removeAttribute() {} load() {} };
require('../pronunciation.js');
(async () => {
  const calls = [];
  const engine = { speak: async (text, opts) => { calls.push({ text, opts }); return { wav: new Blob(['wav']) }; } };
  const voice = global.KawaiiPronunciationModule.create({ getEngine: () => engine, getPrefs: () => ({ zenHappy: 60, zenSpeed: 1.1, zenPitch: 0 }) });
  await voice.speakKana('あ');
  assert.equal(calls[0].text, 'あ');
  assert.deepEqual(calls[0].opts.emotion, { happy: 0, neutral: 100 });
  await voice.speakKana('カ');
  assert.equal(calls[1].text, 'カ');
  await voice.speakKana('きゃ', { clearMora: 'きゃ' });
  assert.equal(calls[2].text, 'きゃ');
  await voice.speakKana('あ', { clearMora: 'あ', sampleJa: 'あさ' }, 'with-word');
  assert.equal(calls[3].text, 'あ。あさ。', 'with-word sample remains unchanged');
  assert.deepEqual(calls[3].opts.emotion, { happy: 0, neutral: 100 });
  await voice.speak('こんにちは。');
  assert.deepEqual(calls[4].opts.emotion, { happy: 60, neutral: 40 }, 'sentence voice remains unchanged');
  console.log('PASS: Kana uses Word Mode without punctuation; with-word sample preserved; sentence unaffected');
})().catch(e => { console.error(e); process.exitCode = 1; });
