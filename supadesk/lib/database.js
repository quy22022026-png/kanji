import { AppError, assert } from "./errors.js";

export function identifier(value) {
  assert(
    typeof value === "string" &&
      value.trim() &&
      !value.includes("\0") &&
      Buffer.byteLength(value) <= 63,
    "Tên bảng/cột/schema phải có từ 1–63 byte, không chứa ký tự NUL.",
  );
  return '"' + value.replaceAll('"', '""') + '"';
}
const qualified = (schema, table) =>
  `${identifier(schema)}.${identifier(table)}`;
const object = (value) =>
  value !== null && typeof value === "object" && !Array.isArray(value);

export const CATALOG_SQL = `
  SELECT n.nspname AS schema, c.relname AS name,
    CASE WHEN c.relkind IN ('r', 'p') THEN 'table' ELSE 'view' END AS kind,
    c.relrowsecurity AS rls
  FROM pg_catalog.pg_class c
  JOIN pg_catalog.pg_namespace n ON n.oid = c.relnamespace
  WHERE c.relkind IN ('r', 'p', 'v', 'm')
    AND n.nspname <> 'information_schema' AND n.nspname !~ '^pg_'
  ORDER BY n.nspname, c.relname`;
export const SCHEMAS_SQL = `
  SELECT nspname AS name FROM pg_catalog.pg_namespace
  WHERE nspname <> 'information_schema' AND nspname !~ '^pg_' ORDER BY nspname`;
export const COLUMNS_SQL = `
  SELECT a.attname AS name, pg_catalog.format_type(a.atttypid, a.atttypmod) AS data_type,
    t.typname AS udt_name, NOT a.attnotnull AS nullable,
    pg_catalog.pg_get_expr(d.adbin, d.adrelid) AS default_value,
    a.attgenerated <> '' AS is_generated, a.attidentity <> '' AS is_identity,
    CASE a.attidentity WHEN 'a' THEN 'ALWAYS' WHEN 'd' THEN 'BY DEFAULT' ELSE NULL END AS identity_generation,
    EXISTS (SELECT 1 FROM pg_catalog.pg_constraint k WHERE k.conrelid = c.oid
      AND k.contype = 'p' AND a.attnum = ANY(k.conkey)) AS primary_key,
    c.relkind IN ('r', 'p') AS writable
  FROM pg_catalog.pg_attribute a
  JOIN pg_catalog.pg_class c ON c.oid = a.attrelid
  JOIN pg_catalog.pg_namespace n ON n.oid = c.relnamespace
  JOIN pg_catalog.pg_type t ON t.oid = a.atttypid
  LEFT JOIN pg_catalog.pg_attrdef d ON d.adrelid = c.oid AND d.adnum = a.attnum
  WHERE n.nspname = $1 AND c.relname = $2 AND a.attnum > 0 AND NOT a.attisdropped
  ORDER BY a.attnum`;

export function columnDefinition(column, allowPrimary = false) {
  assert(object(column), "Thông tin cột không hợp lệ.");
  const name = identifier(column.name);
  const types = new Set([
    "text",
    "bigint",
    "integer",
    "numeric",
    "boolean",
    "uuid",
    "jsonb",
    "date",
    "timestamptz",
  ]);
  assert(types.has(column.type), "Kiểu dữ liệu không được hỗ trợ.");
  const defaults = {
    none: "",
    uuid: "DEFAULT pg_catalog.gen_random_uuid()",
    now: "DEFAULT CURRENT_TIMESTAMP",
    identity: "GENERATED BY DEFAULT AS IDENTITY",
  };
  assert(
    Object.hasOwn(defaults, column.default ?? "none"),
    "Giá trị mặc định không hợp lệ.",
  );
  assert(
    column.default !== "uuid" || column.type === "uuid",
    "UUID tự sinh chỉ dùng cho cột uuid.",
  );
  assert(
    column.default !== "now" || ["date", "timestamptz"].includes(column.type),
    "Thời gian hiện tại chỉ dùng cho date/timestamptz.",
  );
  assert(
    column.default !== "identity" ||
      ["integer", "bigint"].includes(column.type),
    "Số tự tăng chỉ dùng cho integer/bigint.",
  );
  assert(
    allowPrimary || !column.primaryKey,
    "Không thêm khoá chính bằng thao tác này.",
  );
  return `${name} ${column.type} ${defaults[column.default ?? "none"]}${column.nullable === false || column.primaryKey ? " NOT NULL" : ""}`;
}

export function buildCreateTable(input) {
  const table = qualified(input.schema, input.name);
  assert(
    Array.isArray(input.columns) &&
      input.columns.length > 0 &&
      input.columns.length <= 100,
    "Bảng mới cần từ 1–100 cột.",
  );
  assert(
    new Set(input.columns.map((c) => c.name)).size === input.columns.length,
    "Tên cột bị trùng.",
  );
  const definitions = input.columns.map((c) => columnDefinition(c, true));
  const keys = input.columns
    .filter((c) => c.primaryKey)
    .map((c) => identifier(c.name));
  if (keys.length) definitions.push(`PRIMARY KEY (${keys.join(", ")})`);
  // RLS is never disabled through this action; both statements succeed or roll back together.
  return `BEGIN; CREATE TABLE ${table} (${definitions.join(", ")}); ALTER TABLE ${table} ENABLE ROW LEVEL SECURITY; COMMIT;`;
}

export function buildRows(input, columns) {
  const table = qualified(input.schema, input.table);
  assert(
    Number.isInteger(input.limit) && [25, 50, 100].includes(input.limit),
    "Số dòng mỗi trang không hợp lệ.",
  );
  assert(
    Number.isInteger(input.offset) &&
      input.offset >= 0 &&
      input.offset <= 10_000_000,
    "Vị trí trang không hợp lệ.",
  );
  // Preserve int8 and numeric values as strings before JS can round them.
  const parameters = [
    columns
      .filter((c) => ["int8", "numeric"].includes(c.udt_name))
      .map((c) => c.name),
  ];
  const add = (value) => {
    parameters.push(value);
    return `$${parameters.length}`;
  };
  let where = "";
  if (input.filter) {
    const f = input.filter,
      c = columns.find((c) => c.name === f.column);
    assert(c, "Cột lọc không tồn tại.");
    const field = `t.${identifier(c.name)}`;
    if (f.operator === "is_null") where = ` WHERE ${field} IS NULL`;
    else if (f.operator === "eq")
      where = ` WHERE ${field} IS NOT DISTINCT FROM (jsonb_populate_record(NULL::${table}, ${add(JSON.stringify({ [c.name]: f.value }))}::jsonb)).${identifier(c.name)}`;
    else if (f.operator === "ilike") {
      assert(typeof f.value === "string", "Giá trị tìm kiếm không hợp lệ.");
      where = ` WHERE ${field}::text ILIKE ${add(f.value)}`;
    } else assert(false, "Điều kiện lọc không hợp lệ.");
  }
  const keys = columns.filter((c) => c.primary_key);
  const order = keys.length
    ? keys.map((c) => `t.${identifier(c.name)}`).join(", ")
    : "to_jsonb(t)::text";
  const query = `SELECT (
    SELECT jsonb_object_agg(e.key, CASE WHEN e.key = ANY($1::text[])
      THEN to_jsonb(e.value #>> '{}') ELSE e.value END)
    FROM jsonb_each(to_jsonb(t)) e
  ) AS row, md5(row_to_json(t)::text) AS original
  FROM ${table} t${where} ORDER BY ${order} LIMIT ${add(input.limit + 1)} OFFSET ${add(input.offset)}`;
  return { query, parameters };
}

export function buildMutation(action, input, columns) {
  const table = qualified(input.schema, input.table);
  assert(
    columns[0]?.writable,
    "Chỉ sửa dữ liệu trên bảng thường, không sửa view bằng biểu mẫu này.",
  );
  const parameters = [];
  const add = (value) => {
    parameters.push(value);
    return `$${parameters.length}`;
  };
  let names;
  if (action !== "delete") {
    assert(object(input.values), "Dữ liệu dòng không hợp lệ.");
    names = Object.keys(input.values);
    for (const name of names) {
      const column = columns.find((c) => c.name === name);
      assert(column, `Cột ${name} không tồn tại.`);
      assert(
        !column.is_generated &&
          !(column.is_identity && column.identity_generation === "ALWAYS"),
        `Cột ${name} được database tự sinh.`,
      );
      assert(
        action !== "update" || !column.primary_key,
        "Không thay đổi khoá chính trong biểu mẫu sửa dòng.",
      );
      assert(
        input.values[name] !== null || column.nullable,
        `Cột ${name} không cho phép NULL.`,
      );
    }
  }
  if (action === "insert") {
    return {
      query: names.length
        ? `INSERT INTO ${table} (${names.map(identifier).join(", ")}) SELECT ${names.map((n) => `v.${identifier(n)}`).join(", ")} FROM jsonb_populate_record(NULL::${table}, ${add(JSON.stringify(input.values))}::jsonb) v RETURNING 1 AS affected`
        : `INSERT INTO ${table} DEFAULT VALUES RETURNING 1 AS affected`,
      parameters,
    };
  }
  const keys = columns.filter((c) => c.primary_key).map((c) => c.name);
  assert(
    keys.length &&
      object(input.key) &&
      keys.length === Object.keys(input.key).length &&
      keys.every((k) => Object.hasOwn(input.key, k) && input.key[k] !== null),
    "Cần đầy đủ khoá chính để sửa/xoá đúng một dòng.",
  );
  assert(
    typeof input.original === "string" && /^[a-f0-9]{32}$/.test(input.original),
    "Thiếu phiên bản dòng gốc. Làm mới dữ liệu trước khi sửa/xoá.",
  );
  assert(
    action !== "update" || names.length > 0,
    "Chưa có giá trị nào được thay đổi.",
  );
  const valueRecord =
    action === "update"
      ? `jsonb_populate_record(NULL::${table}, ${add(JSON.stringify(input.values))}::jsonb) v, `
      : "";
  const keyRecord = `jsonb_populate_record(NULL::${table}, ${add(JSON.stringify(input.key))}::jsonb) k`;
  const where = `${keys.map((k) => `t.${identifier(k)} IS NOT DISTINCT FROM k.${identifier(k)}`).join(" AND ")} AND md5(row_to_json(t)::text) = ${add(input.original)}`;
  return {
    query:
      action === "update"
        ? `UPDATE ${table} t SET ${names.map((n) => `${identifier(n)} = v.${identifier(n)}`).join(", ")} FROM ${valueRecord}${keyRecord} WHERE ${where} RETURNING 1 AS affected`
        : `DELETE FROM ${table} t USING ${keyRecord} WHERE ${where} RETURNING 1 AS affected`,
    parameters,
  };
}

export function createDatabase(supabase) {
  async function columns(token, ref, input) {
    qualified(input.schema, input.table);
    const rows = await supabase.query(token, ref, COLUMNS_SQL, [
      input.schema,
      input.table,
    ]);
    if (!rows.length)
      throw new AppError(
        404,
        "TABLE_NOT_FOUND",
        "Không tìm thấy cột của bảng hoặc bạn không có quyền xem cấu trúc.",
      );
    return rows;
  }
  async function access(token, ref, input) {
    identifier(input.schema || "public");
    const parameters = [input.schema || "public"];
    const query = `SELECT current_user AS role,
      current_setting('transaction_read_only') = 'on' AS transaction_read_only,
      EXISTS (SELECT 1 FROM pg_catalog.pg_namespace WHERE nspname = $1) AS schema_exists,
      CASE WHEN to_regnamespace($1) IS NULL THEN false ELSE has_schema_privilege(current_user, $1, 'USAGE') END AS schema_usage,
      CASE WHEN to_regnamespace($1) IS NULL THEN false ELSE has_schema_privilege(current_user, $1, 'CREATE') END AS schema_create`;
    const result = { schema: parameters[0] };
    // These probes only SELECT. A successful writer probe is not proof of privileges on every table.
    for (const [name, readOnly] of [
      ["read", true],
      ["write", false],
    ]) {
      try {
        const rows = await supabase.query(
          token,
          ref,
          query,
          parameters,
          readOnly,
        );
        result[name] = { status: "available", ...(rows[0] || {}) };
      } catch (err) {
        if (!(err instanceof AppError)) throw err;
        result[name] = {
          status: err.status === 401 || err.status === 403 ? "denied" : "error",
          code: err.code,
          message: err.message,
          hint: err.hint,
        };
      }
    }
    return result;
  }
  return async function projectAction(token, ref, action, input = {}) {
    assert(object(input), "Tham số thao tác không hợp lệ.");
    if (action === "access") return access(token, ref, input);
    if (action === "catalog") {
      // Sequential to avoid unnecessary concurrent pressure on Management API rate limits.
      const tables = await supabase.query(token, ref, CATALOG_SQL);
      const schemas = await supabase.query(token, ref, SCHEMAS_SQL);
      return { tables, schemas: schemas.map((s) => s.name) };
    }
    if (action === "columns") {
      const list = await columns(token, ref, input);
      return {
        columns: list,
        primaryKeys: list.filter((c) => c.primary_key).map((c) => c.name),
      };
    }
    if (action === "rows") {
      const list = await columns(token, ref, input);
      const built = buildRows(input, list);
      const rows = await supabase.query(
        token,
        ref,
        built.query,
        built.parameters,
      );
      return {
        rows: rows.slice(0, input.limit).map((r) => r.row),
        originals: rows.slice(0, input.limit).map((r) => r.original),
        hasMore: rows.length > input.limit,
      };
    }
    if (["insert", "update", "delete"].includes(action)) {
      const list = await columns(token, ref, input);
      const built = buildMutation(action, input, list);
      const result = await supabase.query(
        token,
        ref,
        built.query,
        built.parameters,
        false,
      );
      if (result.length !== 1)
        throw new AppError(
          409,
          "ROW_CONFLICT",
          "Dòng đã bị thay đổi hoặc xoá kể từ lần tải gần nhất.",
          "Làm mới dữ liệu, xem lại thay đổi rồi lưu lại.",
        );
      return { affected: 1 };
    }
    if (action === "schemaCreate") {
      await supabase.query(token, ref, buildCreateTable(input), [], false);
      return { created: true };
    }
    if (action === "schemaAddColumn" || action === "schemaRenameColumn") {
      const table = qualified(input.schema, input.table);
      const query =
        action === "schemaAddColumn"
          ? `ALTER TABLE ${table} ADD COLUMN ${columnDefinition(input.column)}`
          : `ALTER TABLE ${table} RENAME COLUMN ${identifier(input.from)} TO ${identifier(input.to)}`;
      await supabase.query(token, ref, query, [], false);
      return { changed: true };
    }
    if (action === "sql") {
      assert(
        typeof input.query === "string" &&
          input.query.trim() &&
          input.query.length <= 100_000,
        "SQL phải có nội dung, tối đa 100.000 ký tự.",
      );
      assert(
        typeof input.readOnly === "boolean",
        "Cần chọn rõ chế độ Chỉ đọc hoặc cho phép ghi.",
      );
      const started = performance.now();
      const result = await supabase.query(
        token,
        ref,
        input.query,
        [],
        input.readOnly,
      );
      return {
        rows: result.slice(0, 500),
        rowCount: result.length,
        elapsedMs: Math.round(performance.now() - started),
        truncated: result.length > 500,
      };
    }
    throw new AppError(400, "UNKNOWN_ACTION", "Thao tác không được hỗ trợ.");
  };
}
